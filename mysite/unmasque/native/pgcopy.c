/*
 * pgcopy.c - native threaded backup/restore helper for PRISM.
 *
 * This is a standalone libpq + pthreads executable. Python stays responsible
 * for planning (which tables to copy) and delegates the heavy per-table copies
 * to this binary.
 *
 * Scheduling rule:
 *   - tables with row_count >= --threshold are "large" and are distributed
 *     over up to --max-threads worker threads;
 *   - all remaining "small" tables are handled sequentially by one dedicated
 *     worker, in parallel with the large-table workers.
 *
 * Each worker owns a private PGconn. Every table copy is one transaction:
 *
 *   BEGIN;
 *   DROP TABLE IF EXISTS dst.table CASCADE;
 *   CREATE UNLOGGED TABLE dst.table (LIKE src.table);
 *   INSERT INTO dst.table SELECT * FROM src.table WHERE ...;  -- optional
 *   -- indexes are built AFTER the load, not maintained row by row
 *   COMMIT;
 *
 * Index build failures are reported on INDEX_RESULT lines but do not fail the
 * table copy: source tables are allowed to have no usable index definitions.
 * FAILURES counts copy failures only.
 *
 * With --sql ctas the copy is CREATE UNLOGGED TABLE dst AS SELECT * FROM src
 * (the restore shape used by TPCH_backup_restore.py).
 *
 * Per-table predicates are supplied with repeated --where options:
 *   --where "lineitem=l_quantity < 10" --where "orders=o_totalprice > 100000"
 * The predicate is trusted SQL generated by PRISM, not user input.
 *
 * Build: make -C mysite/unmasque/native
 * Usage: ./pgcopy --help
 */

#define _GNU_SOURCE

#include <libpq-fe.h>
#include <pthread.h>
#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>

#define ERROR_LEN 512

typedef struct {
    char *name;
    char *where;         /* optional trusted SQL predicate, never user data */
    long long rows;
    int is_large;
    int worker;          /* -1 while unassigned */
    int ok;
    long long copied;
    double seconds;
    char error[ERROR_LEN];
    char **index_ddl;    /* retargeted CREATE INDEX statements */
    int nindexes;
} Task;

typedef struct {
    const char *conninfo;
    const char *source;
    const char *dest;
    const char *mode;
    const char *sql;
    long long threshold;
    int max_threads;
    int index_threads;
    int serial;
    int verify;
    int maintenance_work_mem_mb;
    int work_mem_mb;
    Task *tasks;
    int ntasks;
} Options;

typedef struct {
    Options *opt;
    Task **tasks;
    int ntasks;
    int *next;             /* shared cursor for large-table workers */
    pthread_mutex_t *lock;
    int worker_id;
    int small_worker;
} WorkerArg;

static double now_seconds(void)
{
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (double)ts.tv_sec + (double)ts.tv_nsec / 1e9;
}

static void die(const char *fmt, ...)
{
    va_list ap;
    va_start(ap, fmt);
    vfprintf(stderr, fmt, ap);
    va_end(ap);
    fputc('\n', stderr);
    exit(2);
}

static void *xmalloc(size_t n)
{
    void *p = malloc(n);
    if (p == NULL)
        die("out of memory");
    return p;
}

static char *xstrdup(const char *s)
{
    char *p = strdup(s);
    if (p == NULL)
        die("out of memory");
    return p;
}

static char *fmt(const char *format, ...)
{
    va_list ap;
    va_start(ap, format);
    char *out = NULL;
    if (vasprintf(&out, format, ap) < 0)
        die("out of memory");
    va_end(ap);
    return out;
}

/* SQL identifier quoting. Input names are schema/table identifiers, never values. */
static char *quote_ident(const char *name)
{
    size_t n = strlen(name);
    char *out = xmalloc(n * 2 + 3);
    char *p = out;
    *p++ = '"';
    for (size_t i = 0; i < n; i++) {
        if (name[i] == '"')
            *p++ = '"';
        *p++ = name[i];
    }
    *p++ = '"';
    *p = '\0';
    return out;
}

static char *qualified(const char *schema, const char *table)
{
    char *qs = quote_ident(schema);
    char *qt = quote_ident(table);
    char *out = fmt("%s.%s", qs, qt);
    free(qs);
    free(qt);
    return out;
}

static void set_error(char *err, size_t errlen, const char *msg)
{
    if (err != NULL && errlen != 0)
        snprintf(err, errlen, "%s", msg != NULL ? msg : "unknown error");
}

static int exec_sql(PGconn *conn, const char *sql, long long *rows_affected,
                    char *err, size_t errlen)
{
    PGresult *res = PQexec(conn, sql);
    ExecStatusType status = PQresultStatus(res);

    if (status == PGRES_COMMAND_OK || status == PGRES_TUPLES_OK) {
        if (rows_affected != NULL)
            *rows_affected = atoll(PQcmdTuples(res));
        PQclear(res);
        return 1;
    }

    set_error(err, errlen, PQresultErrorMessage(res));
    PQclear(res);
    return 0;
}

static long long query_count(PGconn *conn, const char *qualified_table,
                             const char *where, char *err, size_t errlen)
{
    char *sql = (where != NULL && *where != '\0')
        ? fmt("SELECT count(*) FROM %s WHERE %s", qualified_table, where)
        : fmt("SELECT count(*) FROM %s", qualified_table);
    PGresult *res = PQexec(conn, sql);
    long long value = -1;

    if (PQresultStatus(res) != PGRES_TUPLES_OK) {
        set_error(err, errlen, PQresultErrorMessage(res));
    } else {
        value = atoll(PQgetvalue(res, 0, 0));
    }
    PQclear(res);
    free(sql);
    return value;
}

static void apply_session_settings(PGconn *conn, const Options *opt)
{
    char *sql;
    exec_sql(conn, "SET client_min_messages = warning", NULL, NULL, 0);
    sql = fmt("SET work_mem = '%dMB'", opt->work_mem_mb);
    exec_sql(conn, sql, NULL, NULL, 0);
    free(sql);
    sql = fmt("SET maintenance_work_mem = '%dMB'", opt->maintenance_work_mem_mb);
    exec_sql(conn, sql, NULL, NULL, 0);
    free(sql);
}

/*
 * Collect the source table's index definitions, retargeted to the destination
 * table. pg_indexes.indexdef is a complete CREATE INDEX statement; replace()
 * is literal, not a regex. Indexes are built later by a global index-worker
 * pool so that several independent index builds can run concurrently.
 */
static int collect_indexes(PGconn *conn, const char *src_schema, const char *src_table,
                           const char *dst_schema, const char *dst_table, Task *task,
                           char *err, size_t errlen)
{
    static const char *query =
        "SELECT replace(indexdef, "
        "              ' ON ' || quote_ident($1) || '.' || quote_ident($2) || ' ', "
        "              ' ON ' || quote_ident($3) || '.' || quote_ident($4) || ' ') "
        "FROM pg_indexes WHERE schemaname = $1 AND tablename = $2";

    const char *params[4] = {src_schema, src_table, dst_schema, dst_table};
    PGresult *res = PQexecParams(conn, query, 4, NULL, params, NULL, NULL, 0);

    if (PQresultStatus(res) != PGRES_TUPLES_OK) {
        set_error(err, errlen, PQresultErrorMessage(res));
        PQclear(res);
        return 0;
    }

    int n = PQntuples(res);
    task->nindexes = n;
    task->index_ddl = n > 0 ? xmalloc(sizeof(char *) * (size_t)n) : NULL;
    for (int i = 0; i < n; i++)
        task->index_ddl[i] = xstrdup(PQgetvalue(res, i, 0));
    PQclear(res);
    return 1;
}

static void copy_one_table(PGconn *conn, const Options *opt, Task *task)
{
    double started = now_seconds();
    char err[ERROR_LEN] = {0};
    long long inserted = 0;
    int ok = 1;

    char *dst = qualified(opt->dest, task->name);
    char *src = qualified(opt->source, task->name);
    char *where = (task->where != NULL && *task->where != '\0')
        ? fmt(" WHERE %s", task->where)
        : NULL;
    const char *where_sql = where != NULL ? where : "";

    if (!exec_sql(conn, "BEGIN", NULL, err, sizeof(err)))
        goto fail;

    char *sql = fmt("DROP TABLE IF EXISTS %s CASCADE", dst);
    ok = exec_sql(conn, sql, NULL, err, sizeof(err));
    free(sql);
    if (!ok)
        goto rollback;

    if (strcmp(opt->sql, "ctas") == 0) {
        sql = fmt("CREATE UNLOGGED TABLE %s AS SELECT * FROM %s%s",
                  dst, src, where_sql);
        ok = exec_sql(conn, sql, &inserted, err, sizeof(err));
        free(sql);
        if (!ok)
            goto rollback;
    } else {
        sql = fmt("CREATE UNLOGGED TABLE %s (LIKE %s)", dst, src);
        ok = exec_sql(conn, sql, NULL, err, sizeof(err));
        free(sql);
        if (!ok)
            goto rollback;

        /* Working-schema tables are disposable; keep autovacuum away from them. */
        sql = fmt("ALTER TABLE %s SET (autovacuum_enabled = false)", dst);
        ok = exec_sql(conn, sql, NULL, err, sizeof(err));
        free(sql);
        if (!ok)
            goto rollback;

        sql = fmt("INSERT INTO %s SELECT * FROM %s%s", dst, src, where_sql);
        ok = exec_sql(conn, sql, &inserted, err, sizeof(err));
        free(sql);
        if (!ok)
            goto rollback;
    }

    if (opt->verify) {
        long long dst_rows = query_count(conn, dst, NULL, err, sizeof(err));
        if (dst_rows < 0) {
            ok = 0;
            goto rollback;
        }
        if (task->rows >= 0 && dst_rows != task->rows) {
            ok = 0;
            snprintf(err, sizeof(err), "row count mismatch: expected=%lld destination=%lld",
                     task->rows, dst_rows);
            goto rollback;
        }
        inserted = dst_rows;
    } else if (inserted <= 0 && task->rows > 0) {
        /* PQcmdTuples is authoritative for INSERT; CTAS may not report rows. */
        inserted = task->rows;
    }

    if (!exec_sql(conn, "COMMIT", NULL, err, sizeof(err))) {
        ok = 0;
        goto fail;
    }

    task->ok = 1;
    task->copied = inserted;
    task->seconds = now_seconds() - started;
    free(where);
    free(dst);
    free(src);
    return;

rollback:
    exec_sql(conn, "ROLLBACK", NULL, NULL, 0);
fail:
    task->ok = 0;
    task->copied = 0;
    task->seconds = now_seconds() - started;
    set_error(task->error, sizeof(task->error), err[0] ? err : "copy failed");
    free(where);
    free(dst);
    free(src);
}

static void *worker_main(void *arg)
{
    WorkerArg *w = (WorkerArg *)arg;
    Options *opt = w->opt;
    PGconn *conn = PQconnectdb(opt->conninfo);

    if (PQstatus(conn) != CONNECTION_OK) {
        fprintf(stderr, "worker %d: connection failed: %s\n",
                w->worker_id, PQerrorMessage(conn));
        PQfinish(conn);
        return NULL;
    }

    apply_session_settings(conn, opt);

    if (w->small_worker) {
        for (int i = 0; i < w->ntasks; i++) {
            Task *task = w->tasks[i];
            task->worker = w->worker_id;
            copy_one_table(conn, opt, task);
            if (PQstatus(conn) != CONNECTION_OK)
                PQreset(conn);
        }
    } else {
        for (;;) {
            int index;
            pthread_mutex_lock(w->lock);
            index = (*w->next)++;
            pthread_mutex_unlock(w->lock);
            if (index >= w->ntasks)
                break;

            Task *task = w->tasks[index];
            task->worker = w->worker_id;
            copy_one_table(conn, opt, task);
            if (PQstatus(conn) != CONNECTION_OK)
                PQreset(conn);
        }
    }

    PQfinish(conn);
    return NULL;
}

typedef struct {
    Task *task;
    char *ddl;
    int worker;
    int ok;
    double seconds;
    char error[ERROR_LEN];
} IndexJob;

typedef struct {
    Options *opt;
    IndexJob *jobs;
    int njobs;
    int *next;
    pthread_mutex_t *lock;
    int worker_id;
} IndexWorkerArg;

static void *index_worker_main(void *arg)
{
    IndexWorkerArg *w = (IndexWorkerArg *)arg;
    PGconn *conn = PQconnectdb(w->opt->conninfo);

    if (PQstatus(conn) != CONNECTION_OK) {
        fprintf(stderr, "index worker %d: connection failed: %s\n",
                w->worker_id, PQerrorMessage(conn));
        PQfinish(conn);
        return NULL;
    }
    apply_session_settings(conn, w->opt);

    for (;;) {
        int index;
        pthread_mutex_lock(w->lock);
        index = (*w->next)++;
        pthread_mutex_unlock(w->lock);
        if (index >= w->njobs)
            break;

        IndexJob *job = &w->jobs[index];
        job->worker = w->worker_id;
        double started = now_seconds();
        job->ok = exec_sql(conn, job->ddl, NULL, job->error, sizeof(job->error));
        job->seconds = now_seconds() - started;
        if (!job->ok && PQstatus(conn) != CONNECTION_OK)
            PQreset(conn);
    }

    PQfinish(conn);
    return NULL;
}

static int parse_row_counts(const char *spec, Task *tasks, int ntasks)
{
    if (spec == NULL || *spec == '\0')
        return 1;

    char *copy = xstrdup(spec);
    char *save = NULL;
    char *token = strtok_r(copy, ",", &save);
    while (token != NULL) {
        char *colon = strchr(token, ':');
        if (colon == NULL) {
            free(copy);
            return 0;
        }
        *colon = '\0';
        long long rows = atoll(colon + 1);
        for (int i = 0; i < ntasks; i++) {
            if (strcmp(tasks[i].name, token) == 0) {
                tasks[i].rows = rows;
                break;
            }
        }
        token = strtok_r(NULL, ",", &save);
    }
    free(copy);
    return 1;
}

static int parse_wheres(const char **specs, int nspecs, Task *tasks, int ntasks)
{
    for (int i = 0; i < nspecs; i++) {
        const char *spec = specs[i];
        const char *eq = strchr(spec, '=');
        if (eq == NULL || eq == spec)
            return 0;

        size_t name_len = (size_t)(eq - spec);
        int found = 0;
        for (int j = 0; j < ntasks; j++) {
            if (strlen(tasks[j].name) != name_len ||
                strncmp(tasks[j].name, spec, name_len) != 0)
                continue;
            if (tasks[j].where != NULL)
                return 0;  /* duplicate --where for one table */
            const char *predicate = eq + 1;
            tasks[j].where = (*predicate != '\0') ? xstrdup(predicate) : NULL;
            found = 1;
            break;
        }
        if (!found)
            return 0;
    }
    return 1;
}

static char **split_tables(const char *spec, int *count)
{
    char *copy = xstrdup(spec);
    int capacity = 16;
    int n = 0;
    char **tables = xmalloc(sizeof(char *) * capacity);
    char *save = NULL;
    char *token = strtok_r(copy, ",", &save);

    while (token != NULL) {
        while (*token == ' ' || *token == '\t')
            token++;
        char *end = token + strlen(token);
        while (end > token && (end[-1] == ' ' || end[-1] == '\t'))
            *--end = '\0';
        if (*token != '\0') {
            if (n == capacity) {
                capacity *= 2;
                tables = realloc(tables, sizeof(char *) * capacity);
                if (tables == NULL)
                    die("out of memory");
            }
            tables[n++] = xstrdup(token);
        }
        token = strtok_r(NULL, ",", &save);
    }
    free(copy);
    *count = n;
    return tables;
}

static void usage(const char *prog)
{
    printf(
        "usage: %s --conninfo CONNINFO --source SRC --dest DST --tables LIST [options]\n"
        "\n"
        "options:\n"
        "  --mode backup|restore|copy   label only (default: backup)\n"
        "  --sql like_insert|ctas       copy shape (default: like_insert)\n"
        "  --threshold N                large-table cutoff in rows (default: 100000)\n"
        "  --max-threads N              max large-table workers (default: 4)\n"
        "  --index-threads N            max concurrent index builds (default: 4)\n"
        "  --serial                     one thread, sequential, for baseline\n"
        "  --rows t1:N,t2:N             expected copy row counts; avoids count(*)\n"
        "  --where TABLE=SQL            optional predicate for one table; repeatable\n"
        "                               (SQL is trusted PRISM-generated text)\n"
        "  --no-verify                  skip destination count(*) verification\n"
        "  --maintenance-workmem MB     per-session maintenance_work_mem (default: 512)\n"
        "  --workmem MB                 per-session work_mem (default: 32)\n"
        "\n"
        "The destination schema must already exist. Source tables are only read.\n",
        prog);
}

int main(int argc, char **argv)
{
    Options opt = {
        .conninfo = NULL,
        .source = NULL,
        .dest = NULL,
        .mode = "backup",
        .sql = "like_insert",
        .threshold = 100000,
        .max_threads = 4,
        .index_threads = 4,
        .serial = 0,
        .verify = 1,
        .maintenance_work_mem_mb = 512,
        .work_mem_mb = 32,
        .tasks = NULL,
        .ntasks = 0,
    };
    const char *tables_spec = NULL;
    const char *rows_spec = NULL;
    const char **where_specs = xmalloc(sizeof(char *) * (size_t)argc);
    int nwhere_specs = 0;

    for (int i = 1; i < argc; i++) {
        const char *arg = argv[i];
        if (strcmp(arg, "--help") == 0 || strcmp(arg, "-h") == 0) {
            usage(argv[0]);
            return 0;
        } else if (strcmp(arg, "--conninfo") == 0 && i + 1 < argc) {
            opt.conninfo = argv[++i];
        } else if (strcmp(arg, "--source") == 0 && i + 1 < argc) {
            opt.source = argv[++i];
        } else if (strcmp(arg, "--dest") == 0 && i + 1 < argc) {
            opt.dest = argv[++i];
        } else if (strcmp(arg, "--mode") == 0 && i + 1 < argc) {
            opt.mode = argv[++i];
        } else if (strcmp(arg, "--sql") == 0 && i + 1 < argc) {
            opt.sql = argv[++i];
        } else if (strcmp(arg, "--tables") == 0 && i + 1 < argc) {
            tables_spec = argv[++i];
        } else if (strcmp(arg, "--rows") == 0 && i + 1 < argc) {
            rows_spec = argv[++i];
        } else if (strcmp(arg, "--where") == 0 && i + 1 < argc) {
            where_specs[nwhere_specs++] = argv[++i];
        } else if (strcmp(arg, "--threshold") == 0 && i + 1 < argc) {
            opt.threshold = atoll(argv[++i]);
        } else if (strcmp(arg, "--max-threads") == 0 && i + 1 < argc) {
            opt.max_threads = atoi(argv[++i]);
        } else if (strcmp(arg, "--index-threads") == 0 && i + 1 < argc) {
            opt.index_threads = atoi(argv[++i]);
        } else if (strcmp(arg, "--serial") == 0) {
            opt.serial = 1;
        } else if (strcmp(arg, "--no-verify") == 0) {
            opt.verify = 0;
        } else if (strcmp(arg, "--maintenance-workmem") == 0 && i + 1 < argc) {
            opt.maintenance_work_mem_mb = atoi(argv[++i]);
        } else if (strcmp(arg, "--workmem") == 0 && i + 1 < argc) {
            opt.work_mem_mb = atoi(argv[++i]);
        } else {
            fprintf(stderr, "unknown or incomplete option: %s\n", arg);
            usage(argv[0]);
            return 2;
        }
    }

    if (opt.conninfo == NULL || opt.source == NULL || opt.dest == NULL || tables_spec == NULL) {
        usage(argv[0]);
        return 2;
    }
    if (strcmp(opt.sql, "like_insert") != 0 && strcmp(opt.sql, "ctas") != 0)
        die("--sql must be like_insert or ctas");
    if (opt.max_threads < 1)
        die("--max-threads must be >= 1");
    if (opt.index_threads < 1)
        die("--index-threads must be >= 1");

    int ntables = 0;
    char **table_names = split_tables(tables_spec, &ntables);
    if (ntables == 0)
        die("no tables supplied");

    opt.tasks = xmalloc(sizeof(Task) * ntables);
    opt.ntasks = ntables;
    for (int i = 0; i < ntables; i++) {
        Task *task = &opt.tasks[i];
        memset(task, 0, sizeof(*task));
        task->name = table_names[i];
        task->rows = -1;
        task->worker = -1;
    }

    if (!parse_row_counts(rows_spec, opt.tasks, opt.ntasks))
        die("--rows must look like table:count,table:count");
    if (!parse_wheres(where_specs, nwhere_specs, opt.tasks, opt.ntasks))
        die("--where must look like table=predicate for a listed table");

    double planning_started = now_seconds();
    PGconn *control = PQconnectdb(opt.conninfo);
    if (PQstatus(control) != CONNECTION_OK)
        die("control connection failed: %s", PQerrorMessage(control));
    apply_session_settings(control, &opt);

    for (int i = 0; i < opt.ntasks; i++) {
        if (opt.tasks[i].rows >= 0)
            continue;
        char *src = qualified(opt.source, opt.tasks[i].name);
        char err[ERROR_LEN] = {0};
        long long rows = query_count(control, src, opt.tasks[i].where,
                                     err, sizeof(err));
        free(src);
        if (rows < 0)
            die("could not count %s.%s: %s", opt.source, opt.tasks[i].name, err);
        opt.tasks[i].rows = rows;
    }

    if (strcmp(opt.sql, "ctas") != 0) {
        for (int i = 0; i < opt.ntasks; i++) {
            char err[ERROR_LEN] = {0};
            if (!collect_indexes(control, opt.source, opt.tasks[i].name,
                                 opt.dest, opt.tasks[i].name, &opt.tasks[i],
                                 err, sizeof(err)))
                die("could not collect indexes for %s: %s", opt.tasks[i].name, err);
        }
    }

    PQfinish(control);
    double planning_seconds = now_seconds() - planning_started;

    Task **large = xmalloc(sizeof(Task *) * opt.ntasks);
    Task **small = xmalloc(sizeof(Task *) * opt.ntasks);
    int nlarge = 0, nsmall = 0;
    for (int i = 0; i < opt.ntasks; i++) {
        if (opt.tasks[i].rows >= opt.threshold) {
            opt.tasks[i].is_large = 1;
            large[nlarge++] = &opt.tasks[i];
        } else {
            opt.tasks[i].is_large = 0;
            small[nsmall++] = &opt.tasks[i];
        }
    }

    printf("PLAN\tlarge=%d\tsmall=%d\tthreshold=%lld\tmax_threads=%d\tindex_threads=%d\tserial=%d\tplanning=%.3f\n",
           nlarge, nsmall, opt.threshold, opt.max_threads, opt.index_threads,
           opt.serial, planning_seconds);
    fflush(stdout);

    double copy_started = now_seconds();

    if (opt.serial || nlarge == 0 || (nsmall == 0 && nlarge <= 1)) {
        /* True serial baseline, or not enough independent work to thread. */
        PGconn *conn = PQconnectdb(opt.conninfo);
        if (PQstatus(conn) != CONNECTION_OK)
            die("serial connection failed: %s", PQerrorMessage(conn));
        apply_session_settings(conn, &opt);
        for (int i = 0; i < opt.ntasks; i++) {
            opt.tasks[i].worker = 0;
            copy_one_table(conn, &opt, &opt.tasks[i]);
        }
        PQfinish(conn);
    } else {
        pthread_t small_thread;
        int have_small_thread = 0;
        WorkerArg small_arg;
        pthread_mutex_t lock;
        pthread_mutex_init(&lock, NULL);
        int next = 0;

        int large_workers = opt.max_threads < nlarge ? opt.max_threads : nlarge;
        pthread_t *threads = xmalloc(sizeof(pthread_t) * (size_t)large_workers);
        WorkerArg *args = xmalloc(sizeof(WorkerArg) * (size_t)large_workers);

        if (nsmall > 0) {
            small_arg.opt = &opt;
            small_arg.tasks = small;
            small_arg.ntasks = nsmall;
            small_arg.next = NULL;
            small_arg.lock = NULL;
            small_arg.worker_id = 0;
            small_arg.small_worker = 1;
            if (pthread_create(&small_thread, NULL, worker_main, &small_arg) == 0)
                have_small_thread = 1;
            else
                fprintf(stderr, "could not start small-table worker\n");
        }

        for (int i = 0; i < large_workers; i++) {
            args[i].opt = &opt;
            args[i].tasks = large;
            args[i].ntasks = nlarge;
            args[i].next = &next;
            args[i].lock = &lock;
            args[i].worker_id = i + 1;
            args[i].small_worker = 0;
            if (pthread_create(&threads[i], NULL, worker_main, &args[i]) != 0)
                die("could not start large-table worker %d", i + 1);
        }

        for (int i = 0; i < large_workers; i++)
            pthread_join(threads[i], NULL);
        if (have_small_thread)
            pthread_join(small_thread, NULL);

        pthread_mutex_destroy(&lock);
        free(threads);
        free(args);
    }

    double copy_seconds = now_seconds() - copy_started;

    /* Phase 2: build all indexes with a separate worker pool. Independent
     * CREATE INDEX statements on one table can run concurrently, and indexes
     * from different tables can overlap too. */
    int nindexjobs = 0;
    for (int i = 0; i < opt.ntasks; i++)
        nindexjobs += opt.tasks[i].nindexes;

    double index_seconds = 0.0;
    IndexJob *index_jobs = NULL;
    if (nindexjobs > 0) {
        index_jobs = xmalloc(sizeof(IndexJob) * (size_t)nindexjobs);
        int k = 0;
        for (int i = 0; i < opt.ntasks; i++) {
            Task *task = &opt.tasks[i];
            for (int j = 0; j < task->nindexes; j++) {
                memset(&index_jobs[k], 0, sizeof(index_jobs[k]));
                index_jobs[k].task = task;
                index_jobs[k].ddl = task->index_ddl[j];
                index_jobs[k].worker = -1;
                k++;
            }
        }

        int workers = opt.serial ? 1 : opt.index_threads;
        if (workers > nindexjobs)
            workers = nindexjobs;

        double index_started = now_seconds();
        if (workers <= 1) {
            PGconn *conn = PQconnectdb(opt.conninfo);
            if (PQstatus(conn) != CONNECTION_OK)
                die("index connection failed: %s", PQerrorMessage(conn));
            apply_session_settings(conn, &opt);
            for (int j = 0; j < nindexjobs; j++) {
                IndexJob *job = &index_jobs[j];
                job->worker = 0;
                double started = now_seconds();
                job->ok = exec_sql(conn, job->ddl, NULL, job->error, sizeof(job->error));
                job->seconds = now_seconds() - started;
            }
            PQfinish(conn);
        } else {
            pthread_t *threads = xmalloc(sizeof(pthread_t) * (size_t)workers);
            IndexWorkerArg *args = xmalloc(sizeof(IndexWorkerArg) * (size_t)workers);
            pthread_mutex_t lock;
            pthread_mutex_init(&lock, NULL);
            int next = 0;
            for (int i = 0; i < workers; i++) {
                args[i].opt = &opt;
                args[i].jobs = index_jobs;
                args[i].njobs = nindexjobs;
                args[i].next = &next;
                args[i].lock = &lock;
                args[i].worker_id = i + 1;
                if (pthread_create(&threads[i], NULL, index_worker_main, &args[i]) != 0)
                    die("could not start index worker %d", i + 1);
            }
            for (int i = 0; i < workers; i++)
                pthread_join(threads[i], NULL);
            pthread_mutex_destroy(&lock);
            free(threads);
            free(args);
        }
        index_seconds = now_seconds() - index_started;

        for (int j = 0; j < nindexjobs; j++) {
            IndexJob *job = &index_jobs[j];
            /* Index failures are reported but do not fail the table copy: the
             * source table may have no usable index definition, or the copied
             * data may not satisfy an index the caller does not depend on.
             * Correct row data is the hard requirement. */
            printf("INDEX_RESULT\t%d\t%s\t%.3f\t%d\t%s\n",
                   job->worker, job->task->name, job->seconds, job->ok, job->error);
        }
    }

    int failures = 0;
    int index_failures = 0;
    for (int i = 0; i < nindexjobs; i++) {
        if (!index_jobs[i].ok)
            index_failures++;
    }
    for (int i = 0; i < opt.ntasks; i++) {
        Task *task = &opt.tasks[i];
        if (task->ok)
            continue;
        failures++;
        if (task->worker < 0)
            set_error(task->error, sizeof(task->error), "unassigned (worker connection failure)");
    }

    for (int i = 0; i < opt.ntasks; i++) {
        Task *task = &opt.tasks[i];
        printf("RESULT\t%d\t%s\t%s\t%.3f\t%lld\t%d\t%s\n",
               task->worker, task->is_large ? "large" : "small", task->name,
               task->seconds, task->copied, task->ok, task->error);
    }
    printf("COPY_SECONDS\t%.3f\n", copy_seconds);
    printf("INDEX_SECONDS\t%.3f\n", index_seconds);
    printf("TOTAL_SECONDS\t%.3f\n", planning_seconds + copy_seconds + index_seconds);
    printf("FAILURES\t%d\n", failures);
    printf("INDEX_FAILURES\t%d\n", index_failures);
    fflush(stdout);

    for (int i = 0; i < opt.ntasks; i++) {
        for (int j = 0; j < opt.tasks[i].nindexes; j++)
            free(opt.tasks[i].index_ddl[j]);
        free(opt.tasks[i].index_ddl);
        free(opt.tasks[i].where);
        free(opt.tasks[i].name);
    }
    free(index_jobs);
    free(where_specs);
    free(opt.tasks);
    free(table_names);
    free(large);
    free(small);

    return failures == 0 ? 0 : 1;
}
